const DICTIONARY: Record<Language, Record<string, string>> = {
  es: ES_DICTIONARY,
  en: EN_DICTIONARY,
}

function translate(
  language: Language,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const template = DICTIONARY[language][key] ?? key
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  )
}

const defaultContext: SettingsContextValue = {
  settings: normalizeSettings(undefined),
  updateSettings: () => undefined,
  resetSettings: () => undefined,
  t: (key, vars) => translate('es', key, vars),
}

const SettingsContext = createContext<SettingsContextValue>(defaultContext)

export function SettingsProvider({
  children,
  initialSettings,
  storage,
}: {
  children: ReactNode
  initialSettings?: Settings
  storage?: Storage
}) {
  const [settings, setSettings] = useState<Settings>(
    () => initialSettings ?? loadSettings(storage),
  )

  useEffect(() => {
    saveSettings(settings, storage)
  }, [settings, storage])

  const updateSettings = useCallback((patch: Partial<Settings>) => {
    setSettings((current) => normalizeSettings({ ...current, ...patch }))
  }, [])

  const resetSettings = useCallback(() => {
    setSettings(normalizeSettings(undefined))
  }, [])

  const value = useMemo<SettingsContextValue>(
    () => ({
      settings,
      updateSettings,
      resetSettings,
      t: (key: string, vars?: Record<string, string | number>) =>
        translate(settings.language, key, vars),
    }),
    [settings, updateSettings, resetSettings],
  )

  return <SettingsContext.Provider value={value}>{children}</SettingsContext.Provider>
}

export function useSettings(): SettingsContextValue {
  return useContext(SettingsContext)
}

export function dictionaryFor(language: Language): Record<string, string> {
  return DICTIONARY[language]
}
