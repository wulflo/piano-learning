export type Language = 'es' | 'en'
export type Theme = 'system' | 'light' | 'dark'

export interface Settings {
  notation: Notation
  language: Language
  theme: Theme
  volumeDb: number
  tempo: number
  desiredRetention: number
  maximumInterval: number
  fuzz: boolean
  newPerDay: number
  /** El MIDI todavía no se usa en la app; se conserva para no perderlo al importar. */
  midiEnabled: boolean
  /** Muestra el número de dedo y la mano sobre las teclas con digitación. */
  showFingering: boolean
  computerKeys: Record<string, number>
}

export const SETTINGS_STORAGE_KEY = 'pdc.settings.v1'

export const DEFAULT_SETTINGS: Settings = {
  notation: 'c',
  language: 'es',
  theme: 'light',
  volumeDb: -8,
  tempo: 80,
  desiredRetention: DEFAULT_RETENTION,
  maximumInterval: DEFAULT_MAXIMUM_INTERVAL,
  fuzz: DEFAULT_FUZZ,
  newPerDay: DEFAULT_DAILY_CAP,
  midiEnabled: false,
  showFingering: true,
  computerKeys: { ...DEFAULT_COMPUTER_KEY_MAP },
}

function clamp(value: number, min: number, max: number): number {
  return Math.min(max, Math.max(min, value))
}

function isPlainObject(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

/** Normaliza y valida ajustes leídos de almacenamiento; nunca lanza. */
export function normalizeSettings(input: unknown): Settings {
  if (!isPlainObject(input)) return { ...DEFAULT_SETTINGS, computerKeys: { ...DEFAULT_COMPUTER_KEY_MAP } }
  const notation = input.notation === 'do' ? 'do' : 'c'
  const language = input.language === 'en' ? 'en' : 'es'
  const theme =
    input.theme === 'dark' ? 'dark' : 'light'
  const volumeDb = typeof input.volumeDb === 'number' && Number.isFinite(input.volumeDb)
    ? clamp(input.volumeDb, -40, 0)
    : DEFAULT_SETTINGS.volumeDb
  const tempo = typeof input.tempo === 'number' && Number.isFinite(input.tempo)
    ? clamp(Math.round(input.tempo), 40, 240)
    : DEFAULT_SETTINGS.tempo
  const desiredRetention = normalizeRetention(input.desiredRetention)
  const maximumInterval = normalizeMaximumInterval(input.maximumInterval)
  const fuzz = normalizeFuzz(input.fuzz)
  const newPerDay = normalizeDailyCap(input.newPerDay)
  const midiEnabled = input.midiEnabled === true
  const showFingering = input.showFingering !== false
  const computerKeys: Record<string, number> = isPlainObject(input.computerKeys)
    ? {}
    : { ...DEFAULT_COMPUTER_KEY_MAP }
  if (isPlainObject(input.computerKeys)) {
    for (const [key, midi] of Object.entries(input.computerKeys)) {
      if (
        key.length === 1 &&
        typeof midi === 'number' &&
        Number.isInteger(midi) &&
        midi >= 0 &&
        midi <= 127
      ) {
        computerKeys[key.toLowerCase()] = midi
      }
    }
  }
  return {
    notation,
    language,
    theme,
    volumeDb,
    tempo,
    desiredRetention,
    maximumInterval,
    fuzz,
    newPerDay,
    midiEnabled,
    showFingering,
    computerKeys,
  }
}

export function loadSettings(storage?: Pick<Storage, 'getItem'>): Settings {
  try {
    const target = storage ?? (typeof localStorage === 'undefined' ? undefined : localStorage)
    if (!target) return normalizeSettings(undefined)
    const raw = target.getItem(SETTINGS_STORAGE_KEY)
    if (!raw) return normalizeSettings(undefined)
    return normalizeSettings(JSON.parse(raw))
  } catch {
    return normalizeSettings(undefined)
  }
}

export function saveSettings(
  settings: Settings,
  storage?: Pick<Storage, 'setItem'>,
): void {
  try {
    const target = storage ?? (typeof localStorage === 'undefined' ? undefined : localStorage)
    target?.setItem(SETTINGS_STORAGE_KEY, JSON.stringify(settings))
  } catch {
    // Almacenamiento lleno o bloqueado: la app sigue funcionando en memoria.
  }
}

interface SettingsContextValue {
  settings: Settings
  updateSettings: (patch: Partial<Settings>) => void
  resetSettings: () => void
  t: (key: string, vars?: Record<string, string | number>) => string
}

